#!/usr/bin/env python3
"""Write xiaoji's linker configuration for a rootfs.

Usage: gen-ldconfig.py ROOTFS   (writes ROOTFS/linkerconfig/ld.config.txt and
                                 a copy per APEX at ROOTFS/linkerconfig/<apex>/)

Android normally generates per-APEX, isolated linker namespaces at boot
(linkerconfig, which needs system properties). xiaoji controls the whole guest,
so isolation buys nothing: there is one flat, non-isolated "default" namespace
that can see every library directory. ART and nativeloader still look some
namespaces up by name ("system", and "com_android_<apex>" for each APEX's JNI
libraries), so each of those exists, is visible, and resolves every library
through default, keeping a single instance of libc and friends.
"""
import os, sys

root = sys.argv[1]
apexes = sorted(d for d in os.listdir(os.path.join(root, "apex"))
                if os.path.isdir(os.path.join(root, "apex", d)))
# Search order matters with one flat namespace: the core runtime APEXes, then
# /system, then the other APEXes. The VNDK APEX holds *vendor* builds of system
# libraries (libbinder etc.) with different ABIs, so it is left out.
FIRST = ["com.android.art", "com.android.i18n", "com.android.runtime"]
with_libs = [a for a in apexes if os.path.isdir(os.path.join(root, "apex", a, "lib64"))
             and not a.startswith("com.android.vndk.")]
lib_dirs = [f"/apex/{a}/${{LIB}}" for a in FIRST if a in with_libs]
lib_dirs += ["/system/${LIB}"]
lib_dirs += [f"/apex/{a}/${{LIB}}" for a in with_libs if a not in FIRST]
lib_dirs += ["/system_ext/${LIB}", "/product/${LIB}", "/vendor/${LIB}"]
named = ["system"] + [a.replace(".", "_") for a in apexes]

out = ["# Generated by tools/gen-ldconfig.py; see that file for why it looks like this."]
out += [f"dir.xiaoji = {d}" for d in ("/system", "/system_ext", "/product", "/vendor", "/apex", "/data")]
out += ["", "[xiaoji]", "additional.namespaces = " + ",".join(named),
        "namespace.default.isolated = false",
        "namespace.default.search.paths = " + ":".join(lib_dirs)]
for n in named:
    out += [f"namespace.{n}.isolated = false",
            f"namespace.{n}.visible = true",
            f"namespace.{n}.links = default",
            f"namespace.{n}.link.default.allow_all_shared_libs = true"]
text = "\n".join(out) + "\n"

for sub in [""] + apexes:
    d = os.path.join(root, "linkerconfig", sub)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "ld.config.txt"), "w") as f:
        f.write(text)
print(f"{len(named)} named namespaces, {len(lib_dirs)} library dirs")
