#!/usr/bin/env python3
"""Writes engine/ids_gen.h: the Android AID names (init's user and group options) and the capability
names (init's capabilities option), from the AOSP sources that tools/fetch-remote-ids.sh copies.

  python3 -I tools/gen-ids.py AID_HEADER CAP_UAPI_HEADER INIT_CAPABILITIES_CPP OUT_HEADER

AID_HEADER is system/core/libcutils/include/private/android_filesystem_config.h: its "#define AID_NAME
number" lines give the names (lower-cased, as fs_config does). CAP_UAPI_HEADER is bionic's
linux/capability.h: the numbers. INIT_CAPABILITIES_CPP (system/core/init/capabilities.cpp) lists the names
init accepts in a capabilities line (CAP_MAP_ENTRY(NAME)); each must have a number."""
import re
import sys

aid_h, cap_h, init_cpp, out = sys.argv[1:5]

aid_re = re.compile(r'^#define AID_([A-Z0-9_]+)\s+(\d+)\b')
aids = []
seen = set()
with open(aid_h) as f:
    for line in f:
        m = aid_re.match(line)
        if m and m.group(1) not in seen:
            seen.add(m.group(1))
            aids.append((m.group(1).lower(), int(m.group(2))))

cap_re = re.compile(r'^#define CAP_([A-Z0-9_]+)\s+(\d+)\s*$')
capnum = {}
with open(cap_h) as f:
    for line in f:
        m = cap_re.match(line)
        if m:
            capnum[m.group(1)] = int(m.group(2))

with open(init_cpp) as f:
    names = re.findall(r'CAP_MAP_ENTRY\(([A-Z0-9_]+)\)', f.read())
if not names:
    sys.exit('gen-ids: no CAP_MAP_ENTRY in ' + init_cpp)
caps = []
for n in names:
    if n not in capnum:
        sys.exit('gen-ids: capability %s has no number in %s' % (n, cap_h))
    caps.append((n, capnum[n]))

if not aids:
    sys.exit('gen-ids: no AID entries in ' + aid_h)

lines = [
    '/* Generated by tools/gen-ids.py from the AOSP sources (tools/fetch-remote-ids.sh). Do not edit.',
    ' * AID names: android_filesystem_config.h (bionic-independent; fs_config friendly names).',
    ' * Capability names and numbers: init/capabilities.cpp and bionic linux/capability.h. */',
    '#ifndef XIAOJI_IDS_GEN_H',
    '#define XIAOJI_IDS_GEN_H',
    '',
    'typedef struct {',
    '    const char *name;',
    '    unsigned id;',
    '} ids_entry_t;',
    '',
    'static const ids_entry_t ids_aid[] = {',
]
lines += ['    {"%s", %d},' % (n, v) for n, v in aids]
lines += ['};', '', 'static const ids_entry_t ids_cap[] = {']
lines += ['    {"%s", %d},' % (n, v) for n, v in caps]
lines += ['};', '', '#endif', '']
with open(out, 'w') as f:
    f.write('\n'.join(lines))
print('gen-ids: %d AIDs, %d capabilities -> %s' % (len(aids), len(caps), out))
