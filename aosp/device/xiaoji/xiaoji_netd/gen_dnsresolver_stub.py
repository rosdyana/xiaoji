#!/usr/bin/env python3
# Generates xiaoji_dnsresolver_gen.h from the cpp IDnsResolver.h that the AOSP build produces for
# xiaoji_dnsresolver_aidl-cpp (the copy of the V10 AIDL in aidl/, see Android.bp). ConnectivityService needs the
# binder service "dnsresolver" at its constructor (requireNonNull(dnsresolver)). Every method answers as a no-op:
# there is no DNS path through the engine yet (bionic's resolver needs the dnsproxyd socket, which xiaoji_netd
# does not serve), so names do not resolve through the engine until that path exists.
#
#   python3 gen_dnsresolver_stub.py <path/to/IDnsResolver.h> > xiaoji_dnsresolver_gen.h
import re
import sys

def split_params(s):
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch in "<(":
            depth += 1
        elif ch in ">)":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out

def main():
    text = open(sys.argv[1]).read()
    pat = re.compile(r"virtual ::android::binder::Status (\w+)\((.*?)\) = 0;")
    methods = []
    for m in pat.finditer(text):
        methods.append((m.group(1), split_params(m.group(2))))
    if len(methods) != 14:
        sys.exit("expected 14 Status methods, found %d" % len(methods))

    print("// GENERATED by device/xiaoji/xiaoji_netd/gen_dnsresolver_stub.py from IDnsResolver.h (xiaoji_dnsresolver_aidl-cpp).")
    print("// Do not edit by hand.")
    print("#pragma once")
    print("")
    print("#ifndef LOG_TAG")
    print('#define LOG_TAG "xiaoji_netd"')
    print("#endif")
    print("#include <log/log.h>")
    print("#include <android/net/BnDnsResolver.h>")
    print("")
    print("namespace xiaoji {")
    print("")
    print("class XiaojiDnsResolver : public ::android::net::BnDnsResolver {")
    print("public:")
    for name, params in methods:
        names = [re.search(r"(\w+)\s*$", p).group(1) for p in params]
        sig = ", ".join(params)
        print("    ::android::binder::Status %s(%s) override {" % (name, sig))
        print('        ALOGI("dnsresolver %s: no-op success");' % name)
        for p, n in zip(params, names):
            if "*" in p.rsplit(" ", 1)[0]:
                value = "true" if name == "isAlive" else "{}"
                print("        *%s = %s;" % (n, value))
            else:
                print("        (void)%s;" % n)
        print("        return ::android::binder::Status::ok();")
        print("    }")
    print("};")
    print("")
    print("}  // namespace xiaoji")

if __name__ == "__main__":
    main()
