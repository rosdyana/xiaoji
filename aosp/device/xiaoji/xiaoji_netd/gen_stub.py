#!/usr/bin/env python3
# Generates xiaoji_netd_gen.h from the INetd.h that the AOSP build produces for
# netd_aidl_interface-V10-cpp (the framework's own interface version). Every
# pure virtual Status method of INetd becomes an override in XiaojiNetd. The
# category of each method is decided here; the five boot-path methods listed in
# HAND are defined in xiaoji_netd.cpp.
#
#   python3 gen_stub.py <path/to/INetd.h> > xiaoji_netd_gen.h
import re
import sys

# Implemented by hand in xiaoji_netd.cpp.
HAND = {"isAlive", "interfaceGetList", "interfaceGetCfg", "getProcSysNet", "setProcSysNet"}

# Framework-configured methods: success no-ops (the engine has no kernel to configure).
SUCCESS_PREFIXES = ("firewall", "trafficSwap", "bandwidth", "interface", "network", "tether",
                    "registerUnsolicitedEventListener", "setTcpRWmemorySize")
# Configure-only methods outside those prefixes, found by grepping the framework's callers. The callers catch only
# RemoteException or ServiceSpecificException (NetworkManagementService.setUidCleartextNetworkPolicy and others), so an
# EX_UNSUPPORTED_OPERATION here would reach them as an unchecked exception and crash system_server.
CONFIG_NOOP = {"strictUidCleartextPenalty", "setIPv6AddrGenMode", "wakeupAddInterface", "wakeupDelInterface",
               "idletimerAddInterface", "idletimerRemoveInterface", "socketDestroy", "ipfwdEnableForwarding",
               "ipfwdDisableForwarding", "ipfwdAddInterfaceForward", "ipfwdRemoveInterfaceForward",
               "trafficSetNetPermForUids"}
# Getters with a benign answer (no forwarding, no fwmark): the framework reads them and must get a value.
GETTER_DEFAULT = {"ipfwdEnabled": "false", "ipfwdGetRequesterList": "{}", "getFwmarkForNetwork": "{}"}
# Boolean answers that must not claim success.
FALSE_RESULTS = {"tetherIsEnabled", "networkCanProtect"}

def split_params(s):
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch in "<(":
            depth += 1
        elif ch in ">)":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out

def main():
    text = open(sys.argv[1]).read()
    pat = re.compile(r"virtual ::android::binder::Status (\w+)\((.*?)\)\s*(?:__attribute__\(\(deprecated\(.*?\)\)\)\s*)?=\s*0;")
    methods = []
    for m in pat.finditer(text):
        name, params = m.group(1), split_params(m.group(2))
        methods.append((name, params))
    if len(methods) != 107:
        sys.exit("expected 107 Status methods, found %d" % len(methods))

    print("// GENERATED by device/xiaoji/xiaoji_netd/gen_stub.py from INetd.h (netd_aidl_interface-V10-cpp).")
    print("// Do not edit by hand. Hand-written methods are defined in xiaoji_netd.cpp.")
    print("#pragma once")
    print("")
    print("#ifndef LOG_TAG")
    print('#define LOG_TAG "xiaoji_netd"')
    print("#endif")
    print("#include <log/log.h>")
    print('#include <android/net/BnNetd.h>')
    print('#include <android/net/INetd.h>')
    print("")
    print("namespace xiaoji {")
    print("")
    print("class XiaojiNetd : public ::android::net::BnNetd {")
    print("public:")
    for name, params in methods:
        sig = ", ".join(params)
        head = "    ::android::binder::Status %s(%s) override" % (name, sig)
        if name in HAND:
            print(head + ";")
            continue
        names = [re.search(r"(\w+)\s*$", p).group(1) for p in params]
        out_param = names[-1] if names and names[-1] == "_aidl_return" else None
        body = []
        if name in SUCCESS_PREFIXES or name.startswith(SUCCESS_PREFIXES) or name in CONFIG_NOOP or name in GETTER_DEFAULT:
            body.append('        ALOGI("%s: no-op success");' % name)
            if out_param:
                ptype = params[-1].rsplit(" ", 1)[0] if "*" in params[-1] else ""
                if name in GETTER_DEFAULT:
                    value = GETTER_DEFAULT[name]
                elif name in FALSE_RESULTS:
                    value = "false"
                elif ptype.replace(" ", "") == "bool*":
                    value = "true"
                else:
                    value = "{}"
                body.append("        *%s = %s;" % (out_param, value))
            for n in names:
                if n != out_param:
                    body.append("        (void)%s;" % n)
            body.append("        return ::android::binder::Status::ok();")
        else:
            body.append('        ALOGE("%s: not supported by xiaoji_netd", __func__);')
            for n in names:
                body.append("        (void)%s;" % n)
            body.append("        return ::android::binder::Status::fromExceptionCode(")
            body.append("                ::android::binder::Status::EX_UNSUPPORTED_OPERATION,")
            body.append('                "%s is not supported by xiaoji_netd");' % name)
        print(head + " {")
        print("\n".join(body))
        print("    }")
    print("};")
    print("")
    print("}  // namespace xiaoji")

if __name__ == "__main__":
    main()
