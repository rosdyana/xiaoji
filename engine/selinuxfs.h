/* A synthetic selinuxfs at /sys/fs/selinux (docs/boot.md, B3).
 *
 * SELinux is presented as enabled, permissive (enforce 0) and allow-all. libselinux
 * (sestatus.c, checkAccess.c, compute_av.c, stringrep.c) then runs its real code against
 * this tree. Its is_selinux_enabled() is "selinux_mnt != NULL" on Android, and
 * selinux_status_open() fails without a mount, so the disabled state cannot satisfy
 * servicemanager's CHECK. Every process has the context SELINUX_CTX.
 *
 * The tree is static: directories, read-only files with generated text, the status page
 * (a memfd, mmap-able), and the access file, which answers each request written to it
 * (write, then read). */
#ifndef XIAOJI_SELINUXFS_H
#define XIAOJI_SELINUXFS_H

#include <stddef.h>
#include <stdint.h>

#include "memfd.h"

/* The security context of every process (/proc/<pid>/attr/current, binder secctx). */
#define SELINUX_CTX "u:r:kernel:s0"

/* SELINUX_MAGIC, the f_type of statfs on the mount (verify_selinuxmnt checks it). */
#define SELINUX_MAGIC 0xf97cff8cu

typedef enum {
    SELFS_NONE,
    SELFS_DIR,     /* a directory: listed with selinuxfs_child */
    SELFS_FILE,    /* read-only text, generated by selinuxfs_read */
    SELFS_STATUS,  /* struct selinux_kernel_status, a shared memfd page */
    SELFS_ACCESS   /* write a request, read the reply */
} selfs_kind;

/* What a guest path names in the tree (SELFS_NONE if it is not part of it). */
selfs_kind selinuxfs_kind(const char *guest);

/* The i-th child of a directory: its name and whether it is a directory. Returns 0 if
 * there is no such child (the list ends). */
int selinuxfs_child(const char *dir, int i, const char **name, int *is_dir);

/* Text of a SELFS_FILE (malloc'd). Returns 0, or -1 if the path is not one or out of memory. */
int selinuxfs_read(const char *guest, uint8_t **data, size_t *len);

/* The status page, created on first use (one reference is not taken). NULL if out of memory. */
memfd_t *selinuxfs_status_memfd(void);

/* A request written to the access file, "scon tcon kclass perm" (perm in hex), becomes the
 * reply that the next read returns (malloc'd). Every requested permission is allowed.
 * Returns 0, or -1 for a malformed request or out of memory. */
int selinuxfs_access(const char *req, size_t n, uint8_t **reply, size_t *len);

#endif
