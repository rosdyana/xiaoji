#ifndef XIAOJI_KERNEL_H
#define XIAOJI_KERNEL_H

#include <stddef.h>
#include <stdint.h>

/* The kernel the engine presents (B18): uname's release and version, /proc/version, the KVER(a, b, c) number the
 * bpf loader's version gates compare with, and /proc/config.gz. The release is a GKI one, 5.15.41-android13-8-xiaoji:
 * libvintf takes the kernel FCM level from it (Android 13: level 7) instead of from the product's device manifest
 * (level 5, which allows only 4.14, 4.19 and 5.4; a plain "5.15.41-xiaoji" was refused, docs/boot.md B18), and 5.15.41
 * is the minimum LTS of the level-7 framework compatibility matrix's 5.15 entry. The configuration is what that entry
 * requires (engine/kconfig.inc, generated by tools/gen-kconfig.py from the image's matrices). */
const char *kernel_release(void);
const char *kernel_version(void);
uint32_t kernel_kver(void);
/* /proc/version's text (NUL-terminated, static). */
const char *kernel_proc_version(void);
/* /proc/config.gz: a gzip member (stored deflate blocks) of the configuration text, malloc'd. 0, or -1 (no memory). */
int kernel_config_gz(uint8_t **data, size_t *len);

#endif
